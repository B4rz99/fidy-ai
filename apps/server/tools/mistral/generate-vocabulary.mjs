import { gzipSync } from "node:zlib";

const revision = "b35d4dfe56c142746f54dbd64f579faab2744308";
const sourceUrl = `https://huggingface.co/mistralai/Ministral-3-3B-Instruct-2512/resolve/${revision}/tekken.json`;
const expectedSourceSha256 = "600bb27946565481ecf51ba8aee252e49b9a68507866080ac9c30185bb312843";
const expectedRanksSha256 = "a437159c587e82ed8fc7e0dc7cfd0df5db0e3eccd323ce718bdcb0c0b3674bcf";
const expectedCompressedSha256 = "94190b1851d64902c4e30567e0415fcb27d7f9918c0eace1e0f3de3d070ad418";
const reservedTokenCount = 1_000;
const maximumSourceBytes = 16_000_000;
const downloadDeadlineMilliseconds = 30_000;
const target = new URL(
  "../../src/shell/agent/fixtures/ministral-3b-2512-vocabulary.ts",
  import.meta.url
);

const sha256 = (value) => new Bun.CryptoHasher("sha256").update(value).digest("hex");

export const readBoundedBody = async (response, maximumBytes) => {
  const declaredLength = Number(response.headers.get("content-length"));
  if (Number.isFinite(declaredLength) && declaredLength > maximumBytes) {
    throw new Error("Vocabulary source exceeds its byte limit");
  }
  if (response.body === null) throw new Error("Vocabulary source has no body");
  const reader = response.body.getReader();
  const chunks = [];
  let total = 0;
  while (true) {
    // Stream reads and cancellation are necessarily ordered against the same reader.
    // eslint-disable-next-line no-await-in-loop
    const result = await reader.read();
    if (result.done) break;
    total += result.value.byteLength;
    if (total > maximumBytes) {
      // eslint-disable-next-line no-await-in-loop
      await reader.cancel();
      throw new Error("Vocabulary source exceeds its byte limit");
    }
    chunks.push(result.value);
  }
  const body = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    body.set(chunk, offset);
    offset += chunk.byteLength;
  }
  return body;
};

export const downloadBoundedSource = async (
  url,
  {
    fetchImplementation = fetch,
    maximumBytes = maximumSourceBytes,
    deadlineMilliseconds = downloadDeadlineMilliseconds,
  } = {}
) => {
  const controller = new AbortController();
  const deadline = setTimeout(() => controller.abort(), deadlineMilliseconds);
  try {
    const response = await fetchImplementation(url, { signal: controller.signal });
    if (!response.ok) throw new Error(`Vocabulary download failed with HTTP ${response.status}`);
    return await readBoundedBody(response, maximumBytes);
  } catch (cause) {
    if (controller.signal.aborted) throw new Error("Vocabulary download timed out");
    throw cause;
  } finally {
    clearTimeout(deadline);
  }
};

export const generateVocabulary = async () => {
  const source = Buffer.from(await downloadBoundedSource(sourceUrl));
  if (sha256(source) !== expectedSourceSha256) throw new Error("Pinned vocabulary source changed");

  const document = JSON.parse(source.toString("utf8"));
  const ranks = `${document.vocab
    .map(({ rank, token_bytes: tokenBytes }, index) => {
      if (rank !== index || typeof tokenBytes !== "string") {
        throw new Error("Pinned vocabulary shape is invalid");
      }
      return `! ${rank + reservedTokenCount} ${tokenBytes}`;
    })
    .join("\n")}\n`;
  if (sha256(ranks) !== expectedRanksSha256) throw new Error("Transformed vocabulary changed");

  const compressed = gzipSync(ranks, { level: 9, mtime: 0 });
  if (sha256(compressed) !== expectedCompressedSha256) {
    throw new Error("Compressed vocabulary changed");
  }
  const generated = `/**
 * Generated by tools/mistral/generate-vocabulary.mjs from the pinned official Tekken artifact.
 * Do not edit this representation by hand.
 */
export const ministral3bVocabulary = {
  gzipBase64: ${JSON.stringify(compressed.toString("base64"))},
} as const;
`;
  await Bun.write(target, generated);
};

if (import.meta.main) await generateVocabulary();
